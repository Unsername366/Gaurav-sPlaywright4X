// +, -,*,/,

//Assignment Operator

let a = 10;
let b = 2;

// Arithimatic operator

let sum = a + b;
let sub = a - b;
let mul = a * b;
let div = a / b;

console.log(sum);
console.log(sub);
console.log(mul);
console.log(div);

// Modules -> % -> It will give you remainder

console.log(a % b);
console.log(20 % 3);
console.log(100 % 2);

// Exponential **, power 2^3 -> 8

console.log(2 ** 3);
console.log(4 ** 10);
