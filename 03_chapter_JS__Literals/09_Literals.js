let age = "gaurav"// string literal
let age1 = 20; // number literal 

let isAdult = true; // boolean literal when true or false value is assigned to a variable 
let ischild = false; // boolean literal when true or false value is assigned to a variable

let pi = 3.14; // number literal when decimal value is assigned to a variable
let number = 20; // number literal when integer value is assigned to a variable

let nullValue = null; // null literal when null value is assigned to a variable

let undefinedValue = undefined; // undefined literal when undefined value is assigned to a variabl


// Types of literals in javascript
console.log(typeof age); // string literal
console.log(typeof age1); // number literal
console.log(typeof isAdult); // boolean literal
console.log(typeof ischild); // boolean literal
console.log(typeof pi); // number literal
console.log(typeof number); // number literal
console.log(typeof nullValue); // null literal > comes as a object type in javascript
console.log(typeof undefinedValue); // undefined literal
